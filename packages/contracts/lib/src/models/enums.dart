/// Execution modes governing the privacy boundary.
enum ExecutionMode {
  privateOffline,
  hybrid,
  cloud;

  String toJson() {
    switch (this) {
      case ExecutionMode.privateOffline:
        return 'private_offline';
      case ExecutionMode.hybrid:
        return 'hybrid';
      case ExecutionMode.cloud:
        return 'cloud';
    }
  }

  static ExecutionMode fromJson(String value) {
    switch (value) {
      case 'private_offline':
        return ExecutionMode.privateOffline;
      case 'hybrid':
        return ExecutionMode.hybrid;
      case 'cloud':
        return ExecutionMode.cloud;
      default:
        return ExecutionMode.privateOffline;
    }
  }
}

