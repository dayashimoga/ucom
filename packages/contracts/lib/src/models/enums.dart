/// Real-time conversation state machine.
enum ConversationState {
  idle,
  listening,
  transcribing,
  translating,
  ready,
  speaking;

  String toJson() => name.toUpperCase();

  static ConversationState fromJson(String value) {
    return ConversationState.values.firstWhere(
      (e) => e.name.toUpperCase() == value.toUpperCase(),
      orElse: () => ConversationState.idle,
    );
  }
}

